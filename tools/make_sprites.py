"""Import artist-owned PNG/JSON art into the firmware headers.

Sources (art/):
  theme.json          named colours and which of them the screen chrome uses
  vex/manifest.json   animation order, frame counts, frame timing
  vex/<name>.png      32x32 frames side by side; only theme colours, alpha 0 or 255
  fonts/tiny.png      95 glyphs 5x7 at a 6 px pitch (white = on), characters 32..126
  fonts/display.png   95 glyphs 8x12 at an 8 px pitch

Outputs (firmware/VEX_Pocket_Rival/): theme.h, sprites.h, anim.h, tinyfont.h, displayfont.h;
preview assets/vex_sheet.png. Standard library only. Run from anywhere; use --check to verify the
committed headers match the art without writing.
"""
from pathlib import Path
import json,re,sys
sys.path.insert(0,str(Path(__file__).resolve().parent))
from pngio import decode,encode_rgba

R=Path(__file__).resolve().parents[1];ART=R/'art';FW=R/'firmware/VEX_Pocket_Rival'
SIZE=32;MAX_COLORS=16;TINY=(5,7,6);DISPLAY=(8,12,8)   # glyph w, glyph h, pitch
HEADER='#pragma once\n#include <stdint.h>\n// Generated by tools/make_sprites.py from art/. Edit the PNG/JSON sources, not this file.\n'

class ArtError(SystemExit):pass
def fail(msg):raise ArtError(f'art error: {msg}')
def hex_rgb(s,where):
    if not (isinstance(s,str) and len(s)==7 and s[0]=='#'):fail(f'{where}: colour must be #RRGGBB, got {s!r}')
    return tuple(int(s[i:i+2],16) for i in (1,3,5))
def rgb565(c):return ((c[0]>>3)<<11)|((c[1]>>2)<<5)|(c[2]>>3)

def load_theme():
    t=json.loads((ART/'theme.json').read_text());colors={}
    for name,value in t['colors'].items():
        if not name.isidentifier():fail(f'theme colour name {name!r} must be an identifier')
        colors[name]=hex_rgb(value,f'theme.colors.{name}')
    if len(colors)>MAX_COLORS:fail(f'theme has {len(colors)} colours; the sprite index allows {MAX_COLORS}')
    seen={}
    for n,c in colors.items():
        if c in seen:fail(f'theme colours {seen[c]} and {n} are the same RGB; sprites could not tell them apart')
        seen[c]=n
    ui={}
    for role,name in t['ui'].items():
        if name not in colors:fail(f'theme.ui.{role} refers to unknown colour {name!r}')
        ui[role]=name
    for role in ['bg','ink','gold','red','dim','plum','fade']:
        if role not in ui:fail(f'theme.ui is missing role {role!r}')
    return colors,ui

def display_ms():
    m=re.search(r'DISPLAY_MS\s*=\s*(\d+)',(FW/'config.h').read_text())
    if not m:fail('config.h does not define DISPLAY_MS')
    return int(m.group(1))

def load_manifest():
    m=json.loads((ART/'vex/manifest.json').read_text());period=display_ms()
    if m.get('size',SIZE)!=SIZE:fail(f'manifest size {m.get("size")} unsupported; frames are {SIZE}x{SIZE}')
    anims=m['animations'];names=[a['name'] for a in anims]
    if len(set(names))!=len(names):fail('duplicate animation names in manifest')
    if not anims:fail('manifest lists no animations')
    for a in anims:
        if not a['name'].isidentifier():fail(f'animation name {a["name"]!r} must be an identifier')
        if not (1<=int(a['frames'])<=16):fail(f'{a["name"]}: frames must be 1..16')
        if not (period<=int(a['frame_ms'])<=10000):fail(f'{a["name"]}: frame_ms must be {period}..10000')
        if int(a['frame_ms'])%period:fail(f'{a["name"]}: frame_ms {a["frame_ms"]} is not a multiple of DISPLAY_MS ({period}); frames would repeat or skip')
        if not isinstance(a.get('loop',True),bool):fail(f'{a["name"]}: loop must be true or false')
    return anims

def load_frames(anims,colors):
    """Return (palette names in index order, list of 1024-byte frames). Index 0 is transparent."""
    index={None:0};palette=[None];frames=[];strips={}
    for a in anims:
        path=ART/'vex'/f'{a["name"]}.png'
        if not path.exists():fail(f'{path.relative_to(R)} is missing')
        w,h,px=decode(path.read_bytes());n=int(a['frames'])
        if (w,h)!=(SIZE*n,SIZE):fail(f'{path.name}: expected {SIZE*n}x{SIZE} for {n} frames, got {w}x{h}')
        by_rgb={c:name for name,c in colors.items()}
        for f in range(n):
            frame=bytearray(SIZE*SIZE)
            for y in range(SIZE):
                for x in range(SIZE):
                    r,g,b,alpha=px[y*w+f*SIZE+x]
                    if alpha==0:continue
                    if alpha!=255:fail(f'{path.name} frame {f} pixel ({x},{y}): alpha {alpha}; use fully opaque or fully transparent')
                    name=by_rgb.get((r,g,b))
                    if name is None:fail(f'{path.name} frame {f} pixel ({x},{y}): #{r:02X}{g:02X}{b:02X} is not a theme colour')
                    if name not in index:
                        if len(palette)>=MAX_COLORS:fail(f'sprites use more than {MAX_COLORS-1} colours')
                        index[name]=len(palette);palette.append(name)
                    frame[y*SIZE+x]=index[name]
            frames.append(bytes(frame))
        strips[a['name']]=px
    return palette,frames,strips

def load_font(path,glyph_w,glyph_h,pitch,proportional=False):
    """Column bitmaps per glyph. Proportional fonts are trimmed to their ink columns and left-aligned,
    returning (glyphs, widths); the space keeps a third of the cell."""
    w,h,px=decode(path.read_bytes())
    if (w,h)!=(95*pitch,glyph_h):fail(f'{path.name}: expected {95*pitch}x{glyph_h}, got {w}x{h}')
    glyphs=[];widths=[]
    for g in range(95):
        cols=[]
        for c in range(glyph_w):
            bits=0
            for r in range(glyph_h):
                p=px[r*w+g*pitch+c]
                if p[3]>127 and p[0]>127:bits|=1<<r
            cols.append(bits)
        if proportional:
            ink=[i for i,b in enumerate(cols) if b]
            if ink:cols=cols[ink[0]:ink[-1]+1];cols+=[0]*(glyph_w-len(cols))
            widths.append(len(ink) and ink[-1]-ink[0]+1 or max(2,glyph_w//3))
        glyphs.append(cols)
    return (glyphs,widths) if proportional else glyphs

def generate():
    colors,ui=load_theme();anims=load_manifest();palette,frames,strips=load_frames(anims,colors)
    tiny=load_font(ART/'fonts/tiny.png',*TINY);display,display_widths=load_font(ART/'fonts/display.png',*DISPLAY,proportional=True)
    out={}
    th=HEADER+'namespace vex {\n'
    for name,c in colors.items():th+=f'constexpr uint16_t COLOR_{name.upper()}=0x{rgb565(c):04X}; // #{c[0]:02X}{c[1]:02X}{c[2]:02X}\n'
    for role,name in ui.items():th+=f'constexpr uint16_t UI_{role.upper()}=COLOR_{name.upper()};\n'
    th+='}\n';out['theme.h']=th
    sp=HEADER+f'// {len(frames)} frames of {SIZE}x{SIZE}, one palette index per pixel; index 0 is transparent.\n'
    sp+='static const uint16_t VEX_PALETTE[]={0x0000,'+','.join(f'0x{rgb565(colors[n]):04X}' for n in palette[1:])+'};\n'
    sp+=f'constexpr int VEX_SPRITE_SIZE={SIZE},VEX_SPRITE_COUNT={len(frames)};\n'
    sp+=f'static const uint8_t VEX_SPRITES[VEX_SPRITE_COUNT][{SIZE*SIZE}]={{\n'
    for f in frames:sp+='{'+','.join(str(b) for b in f)+'},\n'
    sp+='};\n';out['sprites.h']=sp
    an=HEADER+'// Animation table: first frame index into VEX_SPRITES, frame count, frame period, loop flag.\n'
    an+='enum VexAnim{'+','.join('ANIM_'+a['name'].upper() for a in anims)+',VEX_ANIM_COUNT};\n'
    an+='struct VexAnimDef{uint8_t first,frames;uint16_t frame_ms;bool loop;};\n'
    an+='static const VexAnimDef VEX_ANIMS[VEX_ANIM_COUNT]={';first=0;rows=[]
    for a in anims:rows.append(f'{{{first},{a["frames"]},{a["frame_ms"]},{"true" if a.get("loop",True) else "false"}}}');first+=int(a['frames'])
    an+=','.join(rows)+'};\n';out['anim.h']=an
    def font_header(name,glyphs,w,h,src,widths=None):
        ctype='unsigned char' if h<=8 else 'unsigned short'
        s=HEADER+f'// {w}x{h} glyphs for characters 32..126, one {ctype} per column, bit n = row n. Source: {src}.\n'
        if widths:s+='// Proportional: glyphs are left-aligned; advance by the width table plus one pixel.\n'
        s+=f'static const {ctype} {name}[95][{w}]={{\n'+'\n'.join('{'+','.join(str(b) for b in g)+'},' for g in glyphs)+'\n};\n'
        if widths:s+=f'static const unsigned char {name}_WIDTH[95]={{'+','.join(str(x) for x in widths)+'};\n'
        return s
    out['tinyfont.h']=font_header('VEX_FONT',tiny,TINY[0],TINY[1],'art/fonts/tiny.png (rasterised from bundled DejaVu Sans Mono; see assets/fonts/LICENSE.txt)')
    out['displayfont.h']=font_header('VEX_DISPLAY_FONT',display,DISPLAY[0],DISPLAY[1],'art/fonts/display.png (rasterised from bundled DejaVu Sans Bold; see assets/fonts/LICENSE.txt)',display_widths)
    return out,colors,ui,anims,palette,frames

def preview(colors,ui,anims,palette,frames,scale=4):
    """Contact sheet of every frame at `scale`, labelled by order, on the UI background."""
    bg=colors[ui['bg']]+(255,);w=SIZE*scale;h=SIZE*scale;cols=len(frames)
    px=[bg]*(w*cols*h)
    for i,f in enumerate(frames):
        for y in range(SIZE):
            for x in range(SIZE):
                k=f[y*SIZE+x]
                if not k:continue
                c=colors[palette[k]]+(255,)
                for dy in range(scale):
                    row=(y*scale+dy)*w*cols+i*w+x*scale
                    for dx in range(scale):px[row+dx]=c
    return encode_rgba(w*cols,h,px)

def main():
    check='--check' in sys.argv
    out,colors,ui,anims,palette,frames=generate()
    stale=[name for name,text in out.items() if not (FW/name).exists() or (FW/name).read_text()!=text]
    if check:
        if stale:raise SystemExit('stale generated headers: '+', '.join(stale)+'; run python3 tools/make_sprites.py')
        print(f'PASS: art/ matches generated headers ({len(frames)} frames, {len(palette)-1} sprite colours, {len(anims)} animations)');return
    for name,text in out.items():(FW/name).write_text(text)
    (R/'assets/vex_sheet.png').write_bytes(preview(colors,ui,anims,palette,frames))
    print(f'Generated {", ".join(out)} from art/: {len(frames)} frames, {len(palette)-1} sprite colours, {len(anims)} animations; preview assets/vex_sheet.png')
if __name__=='__main__':main()
