"""Produce the CAD texture from the same C++ screen renderer used by firmware.

Captures the calibrated, paused pet four seconds after boot (notice expired). Standard library only:
the PNG is written by simulator/frames.py, so no Pillow is required.
"""
from pathlib import Path
import subprocess,sys,tempfile
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'simulator'))
from frames import ppm_png
with tempfile.TemporaryDirectory() as tmp:
    frame=Path(tmp)/'screen.ppm';save=Path(tmp)/'save.bin'
    subprocess.run([str(ROOT/'build/vex-sim'),str(frame),str(save)],input='calibrate\nwait 4000\n',text=True,check=True,capture_output=True)
    (ROOT/'assets/screen.png').write_bytes(ppm_png(frame.read_bytes()))
print('CAD texture generated by shared firmware UI')
