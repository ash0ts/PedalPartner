"""Produce the CAD texture from the same C++ screen renderer used by firmware."""
from pathlib import Path
import subprocess,tempfile
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
with tempfile.TemporaryDirectory() as tmp:
    frame=Path(tmp)/'screen.ppm';save=Path(tmp)/'save.bin'
    subprocess.run([str(ROOT/'build/vex-sim'),str(frame),str(save)],input='calibrate\nstep 4000 0 0 440 1 1\n',text=True,check=True,capture_output=True)
    Image.open(frame).save(ROOT/'assets/screen.png')
print('CAD texture generated by shared firmware UI')
